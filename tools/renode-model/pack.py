#!/usr/bin/env python3
"""Pack the jess Renode model into a DETERMINISTIC, redistributable tarball (jess#299).

    pack.py --version <v> --commit <sha> --out <dir>   ->  <dir>/jess-renode-rt1176-<v>.tar.gz

WHY PYTHON AND NOT `tar`. jess#299 names the GNU tar flags (--sort=name, --mtime, uid/gid 0,
gzip -n). Those are the means; the requirement is that the same inputs give the same bytes.
GNU tar and macOS bsdtar take different flags, so a tar-based packer would be byte-identical on
the release runner and untestable on a developer machine — determinism would first be checked
on a real tag. tarfile + gzip give the same four properties on both, so it is checked locally
and on every PR:
    names sorted            (--sort=name)
    mtime = SOURCE_DATE_EPOCH (--mtime=@$SOURCE_DATE_EPOCH)
    uid/gid 0, no user/group names (--owner=0 --group=0 --numeric-owner)
    gzip header mtime 0, no filename (gzip -n)
plus normalised modes (0644), which tar would otherwise copy from the checkout's umask.

The member set is EXACTLY hardware/renode/MODEL.files, plus LICENSE and a generated
renode-model.toml. Every listed file must exist and be git-tracked: an untracked local file
must not be able to ride into a signed release because it happens to sit in the working tree.
"""
import argparse, gzip, io, os, subprocess, sys, tarfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MODEL_DIR = os.path.join(ROOT, "hardware", "renode")
NAME = "jess-renode-rt1176"
RENODE_TESTED = "1.16.1"
UART_OK = "JESS-RT1176 boot OK"


def model_files():
    out = []
    for line in open(os.path.join(MODEL_DIR, "MODEL.files")):
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    if not out:
        sys.exit("FAIL: MODEL.files lists nothing — refusing to pack an empty model")
    if len(set(out)) != len(out):
        sys.exit("FAIL: MODEL.files lists a path twice")
    return out


def tracked(path):
    return subprocess.run(["git", "-C", ROOT, "ls-files", "--error-unmatch", path],
                          capture_output=True).returncode == 0


def manifest(version, commit):
    # No timestamps: the toml is inside the archive, so anything time-varying here would break
    # determinism for no information gain (the source commit already pins the moment).
    return f"""# Generated by tools/renode-model/pack.py — do not edit inside the archive.
[model]
name = "{NAME}"
version = "{version}"
source-repo = "https://github.com/pulseengine/jess"
source-commit = "{commit}"
license = "Apache-2.0"
platform = "pixhawk6xrt.repl"

[tested-with]
renode = "{RENODE_TESTED}"
# The self-test is checked on BOTH Renode runtimes in jess CI; they differ in how a
# non-zero exit can be raised, and rt1176-smoke-check.resc handles each.
runtimes = ["mono (linux-portable)", "dotnet (linux-portable-dotnet; osx-arm64 dotnet locally)"]

[self-test]
# Needs ONLY Renode — no host Python, no renode-test, no Robot Framework.
command = "renode --console --disable-xwt rt1176-smoke-check.resc"
pass = "exit 0 AND the line 'SMOKE PASS: {UART_OK}'"
exit-codes = {{ 0 = "boot line seen", 3 = "boot line not seen", 4 = "script did not reach a verdict: Renode exited early (e.g. a file failed to load) or the 120 s watchdog fired" }}
# Exit 0 ALONE is not a pass: Renode given a script path that does not exist exits 0 without
# loading anything, so require the line too.

[entry]
interactive = "rt1176-smoke.resc"    # $ORIGIN-relative: runs from any working directory
robot = "rt1176-smoke.robot"         # OPTIONAL extra, for renode-test users; nothing depends on it

[fidelity]
silicon-cross-validated = false
note = '''REQ-PIX-011 - cross-validate this Renode i.MX RT1176 platform against the real
Pixhawk 6X-RT board - is NOT yet verified (status: draft). The model boots the bring-up
firmware and prints on LPUART1; that it reproduces silicon behaviour beyond what jess's
differential oracles exercise is not claimed.'''
"""


def add(tar, arcname, data, epoch):
    ti = tarfile.TarInfo(arcname)
    ti.size = len(data)
    ti.mtime = epoch
    ti.mode = 0o644
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = ""
    ti.type = tarfile.REGTYPE
    tar.addfile(ti, io.BytesIO(data))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    ap.add_argument("--commit", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))

    entries = {}
    missing = []
    for rel in model_files():
        src = os.path.join(MODEL_DIR, rel)
        repo_rel = os.path.relpath(src, ROOT)
        if not os.path.isfile(src):
            missing.append(f"{rel} (absent)")
        elif not tracked(repo_rel):
            missing.append(f"{rel} (not git-tracked)")
        else:
            entries[rel] = open(src, "rb").read()
    if missing:
        sys.exit("FAIL: MODEL.files names file(s) that cannot be packed:\n  " + "\n  ".join(missing))

    lic = os.path.join(ROOT, "LICENSE")
    if not os.path.isfile(lic):
        sys.exit("FAIL: no LICENSE at the repository root — a redistributable archive must carry it")
    for reserved in ("LICENSE", "renode-model.toml"):
        if reserved in entries:
            sys.exit(f"FAIL: MODEL.files lists {reserved}, which the packer adds itself")
    entries["LICENSE"] = open(lic, "rb").read()
    entries["renode-model.toml"] = manifest(a.version, a.commit).encode()

    os.makedirs(a.out, exist_ok=True)
    base = f"{NAME}-{a.version}"
    path = os.path.join(a.out, f"{base}.tar.gz")
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for rel in sorted(entries):
            add(tar, f"{base}/{rel}", entries[rel], epoch)
    with open(path, "wb") as f:
        with gzip.GzipFile(filename="", mode="wb", fileobj=f, mtime=0) as gz:
            gz.write(raw.getvalue())
    print(f"{path}")
    print(f"  {len(entries)} member(s): {len(entries) - 2} from MODEL.files + LICENSE + renode-model.toml")


if __name__ == "__main__":
    main()
